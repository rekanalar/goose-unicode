#!/usr/bin/env python3
"""Make the data file of the LSTM models of ICU 79.1.

The script reads the two default model text files of the ICU library,
release 79.1, and writes the file lstm_data.goose into the package.

The models come from icu4c/source/data/brkitr/lstm of the release. The
files are the Thai_graphclust_model4_heavy and the
Burmese_graphclust_model5_heavy. The script holds no copy of a model.
The NOTICE note under test/ names them.

Each model is a table with a name, a type, an embedding size, a count
of hidden units, a list of strings and an int vector. The int vector
holds the bit patterns of IEEE 754 single floats. The count follows the
formula of lstmbe.cpp of ICU: the embedding table with one extra row,
then for each of the two directions the matrices W and U and the bias,
then the output matrix and the output bias.

The script checks each model after the read. It fails when the count of
the floats differs from the formula. It fails when a string of the list
holds more than 10 UTF-16 units, because the vectorizer of ICU holds 10
units only.

Usage: make_lstm_data.py <dir with the two model text files>
"""
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ucdlib as u

MODELS = [
    ("thai", "Thai_graphclust_model4_heavy.txt", "LSTM_THAI"),
    ("burmese", "Burmese_graphclust_model5_heavy.txt", "LSTM_BURMESE"),
]

# The longest string of the list, in UTF-16 units. The vectorizer of ICU
# holds 10 units.
MAX_UNITS = 10


def read_model(path):
    """The fields of one model: the embedding size, the hidden units,
    the list of strings and the float values."""
    text = open(path, encoding="utf-8-sig").read()
    emb = int(re.search(r"embeddings:int\{(\d+)\}", text).group(1))
    hunits = int(re.search(r"hunits:int\{(\d+)\}", text).group(1))
    kind = re.search(r'type\{"(\w+)"\}', text).group(1)
    if kind != "graphclust":
        u.fail("the model %s has the type %s, and the package uses the "
               "grapheme cluster vectorizer only" % (path, kind))
    body = re.search(r"dict\{(.*?)\n    \}", text, re.S).group(1)
    strings = re.findall(r'"((?:[^"\\]|\\.)*)"', body)
    tail = text[text.index("data:intvector{"):]
    nums = re.findall(r"-?\d+", tail[len("data:intvector{"):])
    values = [struct.unpack("<f", struct.pack("<i", int(n)))[0] for n in nums]
    raw = [int(n) for n in nums]
    want = ((len(strings) + 1) * emb + 2 * (emb * 4 * hunits + hunits * 4 * hunits
            + 4 * hunits) + 2 * hunits * 4 + 4)
    if len(raw) != want:
        u.fail("the model %s holds %d values, and the formula gives %d"
               % (path, len(raw), want))
    units = []
    for s in strings:
        enc = s.encode("utf-16-le")
        if len(enc) // 2 > MAX_UNITS:
            u.fail("the model %s holds a string of %d UTF-16 units, and the "
                   "vectorizer of ICU holds %d" % (path, len(enc) // 2, MAX_UNITS))
        units.append([enc[i] | (enc[i + 1] << 8) for i in range(0, len(enc), 2)])
    return emb, hunits, units, raw


def pack(emb, hunits, units, raw):
    """The bytes of one model: the header, the strings and the values."""
    out = bytearray()
    out += struct.pack("<iii", emb, hunits, len(units))
    for s in units:
        out += struct.pack("<i", len(s))
        for u16 in s:
            out += struct.pack("<H", u16)
    for n in raw:
        out += struct.pack("<i", n)
    return bytes(out)


def main():
    if len(sys.argv) != 2:
        u.fail("usage: make_lstm_data.py <dir with the two model text files>")
    src = sys.argv[1]
    parts = []
    for name, fname, const in MODELS:
        path = os.path.join(src, fname)
        if not os.path.isfile(path):
            u.fail("the model file %s is missing" % path)
        emb, hunits, units, raw = read_model(path)
        data = pack(emb, hunits, units, raw)
        parts.append((const, data))
        print("%s: %d strings, %d floats, %d bytes"
              % (fname, len(units), len(raw), len(data)))
    lines = ["// Generated by test/make_lstm_data.py. Do not edit by hand.",
             "//",
             "// The two default LSTM models of the ICU library, release 79.1. The",
             "// bytes of each model hold the embedding size, the hidden units and",
             "// the count of strings, then the strings as UTF-16 units, then the",
             "// float values as IEEE 754 single patterns.",
             "namespace unicode;",
             ""]
    for const, data in parts:
        lines.append(u.bytes_array(const, data,
                                   "The bytes of the %s model." % const[5:].lower()))
    out = os.path.join(u.ROOT, "lstm_data.goose")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote %s" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
