#!/usr/bin/env python3
"""Make suite/lstm_cases.goose: Thai and Burmese texts with the word and
line breaks of ICU 79.1 when it uses the LSTM models.

Needs: Python 3, ICU 79.1 (headers and libraries) and the genrb tool to
compile the two model files of ICU, Thai_graphclust_model4_heavy and
Burmese_graphclust_model5_heavy.

Usage: make_lstm_cases.py <icu prefix> <icu source> [texts per script]
The script builds test/oracle/csrc/lstmbrk.c, compiles the models into
tmp/lstm_models and asks ICU for the breaks. Each break is the index of a
code point. All code points of the texts lie in the BMP.
"""
import os
import random
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dict_battery as d
import ucdlib as u

MODELS = {"thai": "Thai_graphclust_model4_heavy",
          "burmese": "Burmese_graphclust_model5_heavy"}


def build_oracle(prefix, src):
    work = os.path.join(u.ROOT, "tmp", "lstm_models")
    os.makedirs(os.path.join(work, "icudt79l", "brkitr"), exist_ok=True)
    env = dict(os.environ, LD_LIBRARY_PATH=prefix + "/lib")
    for m in MODELS.values():
        txt = os.path.join(src, "data/brkitr/lstm", m + ".txt")
        subprocess.run([prefix + "/bin/genrb", "-d",
                        os.path.join(work, "icudt79l", "brkitr"), txt],
                       check=True, env=env)
    exe = os.path.join(work, "lstmbrk")
    subprocess.run(["gcc", "-O1", "-o", exe, os.path.join(HERE, "oracle", "csrc", "lstmbrk.c"),
                    "-I" + prefix + "/include", "-L" + prefix + "/lib",
                    "-licuuc", "-licudata"], check=True)
    return exe, work, env


def corpus(name, count, rng):
    words = d.trie_words(d.read_trie(name))
    lo, hi = d.LETTERS[name]
    out = []
    for k in range(count):
        t = []
        for _ in range(rng.randint(1, 8)):
            t += rng.choice(words)[:30]
        if rng.random() < 0.3:
            t.insert(rng.randrange(len(t) + 1), rng.choice(d.MARKS[name]))
        if k % 10 == 0:
            t = [rng.randint(lo, hi) for _ in range(rng.randint(2, 12))]
        out.append(t)
    return out


def ask(exe, work, env, mode, texts):
    env = dict(env, LSTM_DIR=work)
    inp = "\n".join(u.hexline(t) for t in texts) + "\n"
    r = subprocess.run([exe, mode], input=inp, capture_output=True, text=True,
                       check=True, env=env)
    return [[int(x) for x in l.split()] for l in r.stdout.splitlines()]


def main():
    prefix, src = sys.argv[1], sys.argv[2]
    count = int(sys.argv[3]) if len(sys.argv) > 3 else 120
    exe, work, env = build_oracle(prefix, src)
    rng = random.Random(7)
    lines = ["// Generated by test/make_lstm_cases.py. Do not edit by hand.",
             "// Breaks of ICU 79.1 with the LSTM models for Thai and Burmese.",
             "namespace suite;", ""]
    for kind, name in enumerate(["thai", "burmese"]):
        texts = corpus(name, count, rng)
        word = ask(exe, work, env, "word", texts)
        line = ask(exe, work, env, "line", texts)
        for t, w, l in zip(texts, word, line):
            if w[0] != 0 or l[-1] != len(t) or w[-1] != len(t):
                u.fail("unexpected oracle shape")
        tag = "LSTM_" + name.upper()
        for label, vals in (("TXT", texts), ("WORD", [w[:-1] for w in word]),
                            ("LINE", [l[:-1] for l in line])):
            flat, off = [], [0]
            for v in vals:
                flat += v
                off.append(len(flat))
            lines.append("const %s_%s: i64[%d] = [%s];" % (tag, label, len(flat),
                         ", ".join(map(str, flat))))
            lines.append("const %s_%s_OFF: i64[%d] = [%s];" % (tag, label, len(off),
                         ", ".join(map(str, off))))
        lines.append("")
    path = os.path.join(HERE, "suite", "lstm_cases.goose")
    open(path, "w").write("\n".join(lines) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
